APP_WEB_SEARCH_DISABLED_INSTRUCTION = """
【外部検索支援ツールの無効状態（`-WEB`）と案内ルール】
- 現在、AIからの外部検索協力依頼ツール（`request_user_search`）はユーザー設定により無効化（`-WEB`）されています。
- 外部の最新情報や公式ドキュメントの参照が必要で作業を継続できない場合は、自身の古い学習データや推測に基づいて回答せず、作業を中断して以下のように親切に案内してください：
  「現在、AIからの外部検索協力依頼が無効化（`-WEB`）されています。
   外部の最新情報を参照して作業を進める場合は、上部ヘッダーの `-WEB` バッジをクリック（または `/web on` を実行）して有効化するか、該当ドキュメントの内容をプロンプトまたは `/materials` からご提供ください。」
"""

# 後方互換エイリアス
APP_SEARCH_GUIDANCE_INSTRUCTION = APP_WEB_SEARCH_DISABLED_INSTRUCTION


def build_web_search_instruction(enabled: bool) -> str:
    """現在の外部検索支援ツール有効状態（+WEB / -WEB）に対応するインストラクション文字列を返します。"""
    if enabled:
        return APP_WEB_SEARCH_ENABLED_INSTRUCTION.strip()
    return APP_WEB_SEARCH_DISABLED_INSTRUCTION.strip()


